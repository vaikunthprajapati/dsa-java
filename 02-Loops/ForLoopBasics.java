// Print 1 to 100 using for loop
public class ForLoopBasics {
    public static void main(String[] args) {
        for (int i = 1; i <= 100; i++) {
            System.out.print(i + " ");
        }
    }
}

// Print from 55 down to 23 (56 excluded, 23 included)
class ForLoopBasics2 {
    public static void main(String[] args) {
        for (int i = 55; i >= 23; i--) {
            System.out.print(i + " ");
        }
    }
}
